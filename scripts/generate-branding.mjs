/** Generate product artwork from the approved SVG paths, without external fonts or images. */
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const sharp = createRequire(new URL('../apps/desktop/package.json', import.meta.url))('sharp')
const check = process.argv.includes('--check')
const stale = []
const ink = '#172028'
const mark = await readFile(resolve(root, 'assets/branding/harnova-mark.svg'), 'utf8')
const logo = await readFile(resolve(root, 'assets/branding/harnova-logo.svg'), 'utf8')
const paths = svg => [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"/gu)].map(match => match[1])
const markPaths = paths(mark)
const logoPaths = paths(logo)
if (markPaths.length !== 2 || !markPaths.every((path, index) => logoPaths[index] === path)) {
  throw new Error('branding: the approved mark must have two paths matching the logo')
}
const wordPaths = logoPaths.slice(markPaths.length)
const markup = values => values.map(d => `<path d="${d}"/>`).join('')
const tsArray = values => `[\n${values.map(value => `  '${JSON.stringify(value).slice(1, -1).replace(/'/gu, "\\'")}',\n`).join('')}]`
const markArt = markup(markPaths)
const wordArt = markup(wordPaths)
const markBox = '32 32 192 192'
const word = `<g transform="scale(.36) translate(-212 -64)">${wordArt}</g>`
const lockup = `<g transform="translate(-4 -4) scale(.125)">${markArt}</g><g transform="translate(34 3)">${word}</g>`

/** Write a generated artifact, or compare its bytes in check mode. */
async function output(path, contents) {
  const target = resolve(root, path)
  const bytes = Buffer.from(contents)
  if (check) {
    const existing = await readFile(target).catch(error => {
      if (error.code !== 'ENOENT') throw error
      return Buffer.alloc(0)
    })
    if (!existing.equals(bytes)) stale.push(path)
  } else {
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, bytes)
  }
}

/** An SVG with a fixed viewport and no document-global IDs. */
function svg(viewBox, body, color = ink) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="${color}">${body}</svg>\n`
}

/** Rasterize vector artwork at its target size. */
async function png(path, artwork, width, height) {
  await output(path, await sharp(Buffer.from(artwork)).resize(width, height).png().toBuffer())
}

await output('packages/client/ui-primitives/src/brand-artwork.ts',
  `// Generated by scripts/generate-branding.mjs from assets/branding; do not edit.\n// Wordmark outlines use Montserrat Medium; see assets/branding/Montserrat-OFL.txt.\nexport const HARNOVA_MARK_PATHS = ${tsArray(markPaths)} as const\nexport const HARNOVA_WORDMARK_PATHS = ${tsArray(wordPaths)} as const\nexport const HARNOVA_MARK_VIEWBOX = '${markBox}'\n`)

for (const [path, color] of [
  ['apps/web/public/favicon.svg', '#000'],
  ['apps/web/public/favicon-dark.svg', '#fff'],
  ['website/public/favicon.svg', ink],
]) await output(path, svg(markBox, markArt, color))
await output('website/public/wordmark.svg', svg('0 0 148 24', lockup))

const welcomeStyle = '<style>:root{color:#172028}@media(prefers-color-scheme:dark){:root{color:#f9fafb}}</style>'
await output('apps/desktop/renderer/assets/welcome-brand.svg', svg('0 0 148 24', welcomeStyle + lockup, 'currentColor'))

/** Platform tile with the same approved mark and platform-specific outer clearance. */
function appIcon(mac) {
  const edge = mac ? 824 : 960
  const inset = (1024 - edge) / 2
  const markEdge = mac ? 576 : 640
  const markInset = (1024 - markEdge) / 2
  return svg('0 0 1024 1024',
    `<rect x="${inset}" y="${inset}" width="${edge}" height="${edge}" rx="${mac ? 184 : 204}" fill="#f7f8fa"/>` +
    `<g id="tray-glyph"><g transform="translate(${markInset} ${markInset}) scale(${markEdge / 192}) translate(-32 -32)">${markArt}</g></g>`)
}
for (const platform of ['windows', 'macos']) {
  const artwork = appIcon(platform === 'macos')
  await output(`apps/desktop/resources/icon-${platform}.svg`, artwork)
  await png(`apps/desktop/resources/icon-${platform}.png`, artwork, 1024, 1024)
}
await output('apps/desktop/resources/icon.svg', appIcon(false))
await png('apps/desktop/resources/icon.png', appIcon(false), 1024, 1024)

for (const dark of [false, true]) {
  const color = dark ? '#f9fafb' : ink
  const artwork = svg('0 0 600 196', `<g transform="translate(78 62) scale(3)">${lockup}</g>`, color)
  const name = dark ? 'brand-dark' : 'brand'
  await png(`apps/desktop/installer/assets/${name}.png`, artwork, 600, 196)
  await png(`apps/desktop/installer/assets/${name}-2x.png`, artwork, 1200, 392)
}
const sidebar = svg('0 0 164 314',
  '<rect width="164" height="314" fill="#f4f5f7"/>' +
  `<g transform="translate(20 90) scale(.12109375)">${appIcon(false).replace(/^<svg[^>]*>|<\/svg>\s*$/gu, '')}</g>`)
await png('apps/desktop/installer/assets/uninstaller-sidebar.png', sidebar, 164, 314)

/** Diagram artwork instead of screenshots containing upstream logos and personal account details. */
function onboarding(dark, credit) {
  const background = dark ? '#18191c' : '#fff'
  const panel = dark ? '#24262b' : '#f4f5f7'
  const line = dark ? '#60656f' : '#ccd1d9'
  const foreground = dark ? '#f9fafb' : ink
  const controls = [40, 64, 88].map((x, i) => `<circle cx="${x}" cy="28" r="6" fill="${['#ff6259', '#ffc04a', '#2ac84d'][i]}"/>`).join('')
  const rows = [140, 182, 224, 266].map(y => `<rect x="36" y="${y}" width="124" height="8" rx="4" fill="${line}"/>`).join('')
  const center = credit
    ? `<rect x="240" y="110" width="360" height="190" rx="16" fill="${panel}"/><circle cx="292" cy="160" r="24" fill="${line}"/><path d="M278 194Q292 176 306 194" fill="none" stroke="${foreground}" stroke-width="5"/><rect x="338" y="148" width="172" height="10" rx="5" fill="${line}"/><rect x="338" y="170" width="114" height="8" rx="4" fill="${line}"/><rect x="270" y="236" width="132" height="12" rx="6" fill="${line}"/><rect x="470" y="230" width="100" height="28" rx="14" fill="${foreground}"/>`
    : `<g transform="translate(376 112) scale(.375) translate(-32 -32)">${markArt}</g><rect x="270" y="218" width="300" height="74" rx="14" fill="${panel}"/><rect x="290" y="238" width="170" height="8" rx="4" fill="${line}"/><circle cx="542" cy="267" r="12" fill="${foreground}"/>`
  return svg('0 0 660 370', `<rect x="8" y="8" width="644" height="354" rx="24" fill="${background}" stroke="${line}"/>${controls}<rect x="20" y="50" width="180" height="298" rx="14" fill="${panel}"/><g transform="translate(36 72)">${lockup}</g><rect x="36" y="108" width="146" height="18" rx="9" fill="${line}"/>${rows}${center}`, foreground)
}
for (const phase of ['welcome', 'recharge']) {
  for (const language of ['', '-zh']) {
    for (const dark of [false, true]) {
      const artwork = onboarding(dark, phase === 'recharge')
      const name = `onboarding-${phase}${language}${dark ? '-dark' : ''}`
      await png(`packages/client/ui-settings-account/src/client/assets/${name}.png`, artwork, 1320, 740)
    }
  }
}
const prefix = await readFile(resolve(root, 'assets/branding/powered-by.svg'), 'utf8')
const badge = svg('0 0 726 120', '<rect width="726" height="120" fill="#172028"/>' +
  `<g fill="#fff" transform="translate(30 36)">${markup(paths(prefix))}</g><g fill="#fff" transform="translate(365 26) scale(2.5)">${word}</g>`)
await png('packages/skill/skill-badge/assets/dsh-badge.png', badge, 726, 120)
if (stale.length) throw new Error(`branding: stale generated files:\n${stale.join('\n')}`)
console.info(check ? 'branding: generated artwork is current' : 'branding: generated Harnova artwork')
